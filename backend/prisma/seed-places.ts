let defaultClient: PrismaClient | null = null;

export async function seedPlaces(client?: PrismaClient): Promise<number> {
  const db = client ?? (defaultClient ??= new PrismaClient());

  for (const place of places) {
    await db.place.upsert({
      where: { slug: place.slug },
      update: place,
      create: place,
    });
  }

  return places.length;
}

const invokedDirectly = process.argv[1]?.replace(/\\/g, "/").endsWith("seed-places.ts");

if (invokedDirectly) {
  seedPlaces()
    .then((count) => console.log(`✓ ${count} places are ready`))
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    })
    .finally(async () => {
      await defaultClient?.$disconnect();
    });
}
